<#
    09_Mapfiles_BBReborne_Param_CustomTab.ps1

    BBReborne Param Tweaks tab wrapper around the original GParam XML patch applier.

    It applies XML patches generated by 05b_Mapfiles_BBReborne_Param_Development.ps1
    to original *.gparambnd.dcx archives, then repacks them with WitchyBND.

    Expected patch target paths look like:
        m24_02_0000-gparambnd-dcx/m24_02_0000.gparam.xml
        m24_02_0000-gparambnd-dcx/m24_02_0100.gparam.xml

    That maps back to:
        m24_02_0000.gparambnd.dcx

    If the original archive was under a subfolder, the same relative structure is
    preserved:
        drawparam/m24_02_0000.gparambnd.dcx
        drawparam/m24_02_0000-gparambnd-dcx/m24_02_0000.gparam.xml

    Notes:
    Tool defaults:
    - PatchDir defaults to <ProjectRoot>\Diffs\param\drawparam.
    - OriginalDir defaults to <GameRoot>\param\drawparam.
    - OutputDir defaults to <OutputRoot>\BBReborne_param\param\drawparam.
    - MapCode M21 filters patches to ParamPrefix m21_.

    Important:
    - This script intentionally operates only on *.gparambnd.dcx archives.
      Loose *.gparam.dcx files in drawparam are ignored by the matcher.
    - PatchDir is read-only input.
    - OriginalDir is read-only input.
    - OutputDir receives patched/repacked archives and scratch work.
    - Only the safe scratch folder leaf named by -WorkDirName may be deleted/recreated.
#>

