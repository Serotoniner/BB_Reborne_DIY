function Set-GparamLightValuesInXmlFile {
    param(
        [Parameter(Mandatory=$true)][string]$XmlPath,
        [Parameter(Mandatory=$true)][string]$XmlRelPosix,
        [Parameter(Mandatory=$true)]$SourceValues,
        [Parameter(Mandatory=$true)][string]$LightSourceLabel
    )

    $lines = [System.IO.File]::ReadAllLines($XmlPath)
    $out = New-Object System.Collections.Generic.List[string]

    $active = $false
    $activeName1 = ""
    $activeName2 = ""
    $applied = 0
    $changed = 0
    $missing = 0

    foreach ($line in $lines) {
        $content = [string]$line

        if ($content -match '<param\b') {
            $name1 = Get-GparamXmlAttrValue -Text $content -AttrName 'name1'
            $name2 = Get-GparamXmlAttrValue -Text $content -AttrName 'name2'
            if (Test-GparamLightTargetParamName -Name1 $name1 -Name2 $name2) {
                $active = $true
                $activeName1 = $name1
                $activeName2 = $name2
            }
            else {
                $active = $false
                $activeName1 = ""
                $activeName2 = ""
            }

            if ($content -match '/>\s*$') {
                $active = $false
                $activeName1 = ""
                $activeName2 = ""
            }
        }

        $newLine = [string]$line
        if ($active -and $content -match '^(.*<value\s+id=")([^"]+)(">\s*)(.*?)(\s*</value>.*)$') {
            $id = [string]$Matches[2]
            $oldValue = [string]$Matches[4]
            $key = Get-GparamLightValueKey -XmlRelPosix $XmlRelPosix -ParamName1 $activeName1 -ValueId $id

            if ($SourceValues.ContainsKey($key)) {
                $newValue = [string]$SourceValues[$key]
                $applied++
                if ($oldValue -ne $newValue) {
                    $newLine = $Matches[1] + $id + $Matches[3] + $newValue + $Matches[5]
                    $changed++
                }
            }
            else {
                $missing++
            }
        }

        [void]$out.Add($newLine)

        if ($active -and $content -match '</param>') {
            $active = $false
            $activeName1 = ""
            $activeName2 = ""
        }
    }

    if ($changed -gt 0) {
        Write-GparamTextFileAtomic -Path $XmlPath -Text ((($out.ToArray()) -join "`n") + "`n")
    }

    return [pscustomobject]@{
        LightSource = $LightSourceLabel
        XmlRel = ConvertTo-PosixPath $XmlRelPosix
        XmlPath = $XmlPath
        AppliedRows = $applied
        ChangedRows = $changed
        MissingSourceRows = $missing
    }
}

function Find-GparamXmlPatchFiles {
    param(
        [Parameter(Mandatory=$true)][string]$Root,
        [ValidateSet("AutoDedup","FinalRepoOnly","StagedFilesOnly","DirectPatchDirOnly")]
        [string]$Mode = "AutoDedup"
    )

    $rootFull = [IO.Path]::GetFullPath($Root)
    $found = [System.Collections.Generic.List[object]]::new()

    function Add-PatchesFromDir([string]$Dir, [bool]$Recursive) {
        if (-not (Test-Path -LiteralPath $Dir -PathType Container)) { return }

        $gci = @{ LiteralPath=$Dir; File=$true; Filter="*.gparam.xml.patch"; ErrorAction="SilentlyContinue" }
        if ($Recursive) { $gci.Recurse = $true }

        Get-ChildItem @gci |
            Where-Object { $_.Length -gt 0 } |
            Where-Object { -not (Test-IsGeneratedScratchPath $_.FullName) } |
            ForEach-Object { [void]$found.Add($_) }
    }

    function Add-FinalRepoPatchesFromRoot([string]$Dir) {
        if (-not (Test-Path -LiteralPath $Dir -PathType Container)) { return }

        if ((Split-Path -Leaf $Dir) -eq "_patches") {
            Add-PatchesFromDir -Dir $Dir -Recursive $false
            return
        }

        $childPatches = Join-Path $Dir "_patches"
        if (Test-Path -LiteralPath $childPatches -PathType Container) {
            Add-PatchesFromDir -Dir $childPatches -Recursive $false
        }

        Get-ChildItem -LiteralPath $Dir -Directory -Filter "_patches" -Recurse -ErrorAction SilentlyContinue |
            Where-Object {
                $rel = ([IO.Path]::GetRelativePath($Dir, $_.FullName) -replace '\\','/')
                $rel -notmatch '(^|/)files/'
            } |
            ForEach-Object {
                Add-PatchesFromDir -Dir $_.FullName -Recursive $false
            }
    }

    function Add-StagedFilesPatchesFromRoot([string]$Dir) {
        if (-not (Test-Path -LiteralPath $Dir -PathType Container)) { return }

        $leaf = Split-Path -Leaf $Dir
        $filesRoot = if ($leaf -eq "files") { $Dir } else { Join-Path $Dir "files" }

        if (Test-Path -LiteralPath $filesRoot -PathType Container) {
            Add-PatchesFromDir -Dir $filesRoot -Recursive $true
        }
    }

    switch ($Mode) {
        "DirectPatchDirOnly" {
            Add-PatchesFromDir -Dir $rootFull -Recursive $false
        }

        "FinalRepoOnly" {
            Add-FinalRepoPatchesFromRoot -Dir $rootFull
        }

        "StagedFilesOnly" {
            Add-StagedFilesPatchesFromRoot -Dir $rootFull
        }

        "AutoDedup" {
            Add-FinalRepoPatchesFromRoot -Dir $rootFull
            Add-StagedFilesPatchesFromRoot -Dir $rootFull

            # Accept older _patches\files layout.
            if ((Split-Path -Leaf $rootFull) -eq "_patches") {
                Add-PatchesFromDir -Dir (Join-Path $rootFull "files") -Recursive $true
            }

            $childPatches = Join-Path $rootFull "_patches"
            if (Test-Path -LiteralPath $childPatches -PathType Container) {
                Add-PatchesFromDir -Dir (Join-Path $childPatches "files") -Recursive $true
            }

            # Fallback for hand-copied direct patch files.
            if ($found.Count -eq 0) {
                Add-PatchesFromDir -Dir $rootFull -Recursive $true
            }
        }
    }

    return @($found | Sort-Object FullName -Unique)
}

function Invoke-NativeChecked {
    param(
        [Parameter(Mandatory=$true)][string]$Exe,
        [Parameter(Mandatory=$true)][string[]]$Arguments,
        [string]$WorkingDirectory = "",
        [int[]]$AllowedExitCodes = @(0),
        [string]$Label = "native command"
    )

    if (-not [string]::IsNullOrWhiteSpace($WorkingDirectory)) { Push-Location -LiteralPath $WorkingDirectory }
    try {
        & $Exe @Arguments | Out-Null
        $code = $LASTEXITCODE
        if ($AllowedExitCodes -notcontains $code) {
            throw "$Label failed with exit code $code. Command: $Exe $($Arguments -join ' ')"
        }
    }
    finally {
        if (-not [string]::IsNullOrWhiteSpace($WorkingDirectory)) { Pop-Location }
    }
}

function Invoke-WitchyBatchSimple {
    param(
        [Parameter(Mandatory=$true)][string]$Exe,
        [Parameter(Mandatory=$true)][string[]]$Paths,
        [int]$BatchSize = 50,
        [string]$Label = "WitchyBND"
    )

    $total = $Paths.Count
    if ($total -eq 0) { return }

    for ($start = 0; $start -lt $total; $start += $BatchSize) {
        $endExclusive = [Math]::Min($start + $BatchSize, $total)
        $batch = @($Paths[$start..($endExclusive - 1)])
        $batchNum = [int]([Math]::Floor($start / $BatchSize) + 1)
        Write-Host ("  {0} batch {1}: files {2}-{3} ({4} files)" -f $Label, $batchNum, ($start + 1), $endExclusive, $batch.Count)
        Invoke-NativeChecked -Exe $Exe -Arguments $batch -Label "$Label batch $batchNum"
    }
}

function Invoke-GitApplyPatch {
    param(
        [Parameter(Mandatory=$true)][string]$GitExe,
        [Parameter(Mandatory=$true)][string]$PatchPath,
        [Parameter(Mandatory=$true)][string]$WorkRoot,
        [Parameter(Mandatory=$true)][string]$XmlRelPosix,
        [switch]$PreferThreeWay
    )

    $xmlRelWin = ConvertTo-WindowsRelPath $XmlRelPosix
    $targetXml = Join-Path $WorkRoot $xmlRelWin

    if (-not (Test-Path -LiteralPath $targetXml -PathType Leaf)) {
        throw "Patch target XML is missing: $targetXml"
    }

    $backupXml = "$targetXml.__prepatch__"
    Copy-Item -LiteralPath $targetXml -Destination $backupXml -Force

    if ($PreferThreeWay) {
        $attempts = @(
            [pscustomobject]@{ Name="3way"; Args=@("apply", "-p1", "--3way", "--recount", "--whitespace=nowarn", "--", $PatchPath) },
            [pscustomobject]@{ Name="strict"; Args=@("apply", "-p1", "--recount", "--whitespace=nowarn", "--", $PatchPath) },
            [pscustomobject]@{ Name="ignore-space"; Args=@("apply", "-p1", "--recount", "--whitespace=nowarn", "--ignore-space-change", "--ignore-whitespace", "--", $PatchPath) },
            [pscustomobject]@{ Name="reject-diagnostic"; Args=@("apply", "-p1", "--reject", "--recount", "--whitespace=nowarn", "--", $PatchPath) }
        )
    }
    else {
        $attempts = @(
            [pscustomobject]@{ Name="strict"; Args=@("apply", "-p1", "--recount", "--whitespace=nowarn", "--", $PatchPath) },
            [pscustomobject]@{ Name="ignore-space"; Args=@("apply", "-p1", "--recount", "--whitespace=nowarn", "--ignore-space-change", "--ignore-whitespace", "--", $PatchPath) },
            [pscustomobject]@{ Name="3way"; Args=@("apply", "-p1", "--3way", "--recount", "--whitespace=nowarn", "--", $PatchPath) },
            [pscustomobject]@{ Name="reject-diagnostic"; Args=@("apply", "-p1", "--reject", "--recount", "--whitespace=nowarn", "--", $PatchPath) }
        )
    }

    $lastExit = $null
    $lastFirstLine = ""
    $lastAttempt = ""

    Push-Location -LiteralPath $WorkRoot
    try {
        foreach ($attempt in $attempts) {
            Copy-Item -LiteralPath $backupXml -Destination $targetXml -Force

            $oldRejects = @(Get-ChildItem -LiteralPath $WorkRoot -Recurse -File -Filter "*.rej" -ErrorAction SilentlyContinue)
            foreach ($rej in $oldRejects) { Remove-Item -LiteralPath $rej.FullName -Force -ErrorAction SilentlyContinue }

            $out = @(& $GitExe @($attempt.Args) 2>&1)
            $code = $LASTEXITCODE

            $lastExit = $code
            $lastFirstLine = (($out | Select-Object -First 1) -join "")
            $lastAttempt = $attempt.Name

            if ($code -eq 0 -and $attempt.Name -ne "reject-diagnostic") {
                Remove-Item -LiteralPath $backupXml -Force -ErrorAction SilentlyContinue
                return [pscustomobject]@{
                    Ok = $true
                    XmlRel = $XmlRelPosix
                    PatchPath = $PatchPath
                    Attempt = $attempt.Name
                    Message = ""
                    RejectFiles = ""
                }
            }
        }
    }
    finally {
        Pop-Location
    }

    Copy-Item -LiteralPath $backupXml -Destination $targetXml -Force
    Remove-Item -LiteralPath $backupXml -Force -ErrorAction SilentlyContinue

    $rejects = @(Get-ChildItem -LiteralPath $WorkRoot -Recurse -File -Filter "*.rej" -ErrorAction SilentlyContinue | ForEach-Object { $_.FullName })

    return [pscustomobject]@{
        Ok = $false
        XmlRel = $XmlRelPosix
        PatchPath = $PatchPath
        Attempt = $lastAttempt
        Message = "git apply failed. LastAttempt=$lastAttempt Exit=$lastExit Message=$lastFirstLine"
        RejectFiles = ($rejects -join ";")
    }
}

