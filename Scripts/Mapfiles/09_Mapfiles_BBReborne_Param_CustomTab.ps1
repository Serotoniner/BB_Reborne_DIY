function Get-PatchSelectionRank([string]$PatchPath, [string]$Root) {
    # Lower rank wins. Prefer final repository layout over staged files\ layout.
    $rel = ([IO.Path]::GetRelativePath($Root, $PatchPath) -replace '\\','/')
    if ($rel -match '(^|/)(_gparam_patch_apply_work|_gparam_patch_work|_patch_apply_work|_patch_work|_normalized_patches)(/|$)') { return 1000 }
    if ($rel -match '(^|/)files/') { return 20 }
    if ($rel -match '(^|/)_patches/') { return 10 }
    if ($rel -match '/_patches/') { return 10 }
    return 50
}

function Get-APathFromPatchHeader([string]$PatchPath) {
    $lines = Get-Content -LiteralPath $PatchPath -TotalCount 80
    foreach ($line in $lines) {
        if ($line -notmatch '^diff --git\s+') { continue }

        $m = [regex]::Match($line, '^diff --git\s+("([^"]+)"|(\S+))\s+("([^"]+)"|(\S+))\s*$')
        if (-not $m.Success) { return $null }
        if ($m.Groups[2].Success) { return $m.Groups[2].Value }
        return $m.Groups[3].Value
    }

    return $null
}

function Get-XmlRelFromPatch([string]$PatchPath) {
    $aToken = Get-APathFromPatchHeader $PatchPath
    if (-not $aToken) { return $null }

    $p = $aToken -replace '\\','/'
    $p = $p -replace '^(a|b)/',''
    return $p
}

function Get-GparamArchiveInfoFromXmlRel([string]$XmlRel) {
    $posix = ConvertTo-PosixPath $XmlRel
    $parts = @($posix -split '/' | Where-Object { -not [string]::IsNullOrWhiteSpace($_) })

    for ($i = 0; $i -lt $parts.Count; $i++) {
        if ($parts[$i] -match '(?i)-gparambnd-dcx$') {
            $folderLeaf = $parts[$i]
            $archiveLeaf = ($folderLeaf -replace '(?i)-gparambnd-dcx$', '.gparambnd.dcx')

            $prefix = @()
            if ($i -gt 0) { $prefix = @($parts[0..($i - 1)]) }

            $archiveParts = @($prefix + @($archiveLeaf))
            $folderParts  = @($prefix + @($folderLeaf))

            return [pscustomobject]@{
                XmlRelPosix = $posix
                ArchiveRelPosix = [string]::Join('/', $archiveParts)
                ArchiveRelWin = ConvertTo-WindowsRelPath ([string]::Join('/', $archiveParts))
                ExtractFolderRelPosix = [string]::Join('/', $folderParts)
                ExtractFolderRelWin = ConvertTo-WindowsRelPath ([string]::Join('/', $folderParts))
                ExtractFolderLeaf = $folderLeaf
                ArchiveLeaf = $archiveLeaf
            }
        }
    }

    throw "Could not infer .gparambnd.dcx archive from patch target path: $XmlRel"
}


function Test-GparamLightTargetParamName {
    param(
        [string]$Name1 = "",
        [string]$Name2 = ""
    )

    foreach ($name in @($Name1, $Name2)) {
        if ([string]::IsNullOrWhiteSpace($name)) { continue }
        if ($name -match '(?i)\b(DiffColor|SpecColor)\d*\b') { return $true }
        if ($name -match '(?i)\bHemi\s+Color\s+(Up|Down)\b') { return $true }
    }

    return $false
}

