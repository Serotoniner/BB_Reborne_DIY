}

function Read-GparamLightValuesFromXmlFile {
    param(
        [Parameter(Mandatory=$true)][string]$XmlPath,
        [Parameter(Mandatory=$true)][string]$XmlRelPosix,
        [Parameter(Mandatory=$true)][string]$SourceLabel
    )

    $values = @{}
    $rows = [System.Collections.Generic.List[object]]::new()
    $lines = [System.IO.File]::ReadAllLines($XmlPath)

    $active = $false
    $activeName1 = ""
    $activeName2 = ""

    foreach ($line in $lines) {
        $content = [string]$line

        if ($content -match '<param\b') {
            $name1 = Get-GparamXmlAttrValue -Text $content -AttrName 'name1'
            $name2 = Get-GparamXmlAttrValue -Text $content -AttrName 'name2'
            if (Test-GparamLightTargetParamName -Name1 $name1 -Name2 $name2) {
                $active = $true
                $activeName1 = $name1
                $activeName2 = $name2
            }
            else {
                $active = $false
                $activeName1 = ""
                $activeName2 = ""
            }

            if ($content -match '/>\s*$') {
                $active = $false
                $activeName1 = ""
                $activeName2 = ""
            }
        }

        if ($active -and $content -match '<value\s+id="([^"]+)">\s*(.*?)\s*</value>') {
            $id = [string]$Matches[1]
            $value = [string]$Matches[2]
            $key = Get-GparamLightValueKey -XmlRelPosix $XmlRelPosix -ParamName1 $activeName1 -ValueId $id
            $values[$key] = $value
            [void]$rows.Add([pscustomobject]@{
                Source = $SourceLabel
                XmlRel = ConvertTo-PosixPath $XmlRelPosix
                ParamName1 = $activeName1
                ParamName2 = $activeName2
                ValueId = $id
                Value = $value
                XmlPath = $XmlPath
            })
        }

        if ($active -and $content -match '</param>') {
            $active = $false
            $activeName1 = ""
            $activeName2 = ""
        }
    }

    return [pscustomobject]@{
        Values = $values
        Rows = @($rows.ToArray())
    }
}

function Add-GparamLightValuesToTable {
    param(
        [Parameter(Mandatory=$true)]$TargetTable,
        [Parameter(Mandatory=$true)]$TargetRows,
        [Parameter(Mandatory=$true)]$ReadResult
    )

    foreach ($k in @($ReadResult.Values.Keys)) {
        $TargetTable[$k] = $ReadResult.Values[$k]
    }

    foreach ($r in @($ReadResult.Rows)) {
        [void]$TargetRows.Add($r)
    }
}

function Resolve-GparamLightSourceXmlPath {
    param(
        [Parameter(Mandatory=$true)][string]$SourceRoot,
        [Parameter(Mandatory=$true)][string]$XmlRelPosix
    )

    $rootFull = [IO.Path]::GetFullPath($SourceRoot)
    $relWin = ConvertTo-WindowsRelPath $XmlRelPosix
    $direct = Join-Path $rootFull $relWin
    if (Test-Path -LiteralPath $direct -PathType Leaf) { return $direct }

    $leaf = Split-Path -Leaf $relWin
    $relNeedle = '/' + (ConvertTo-PosixPath $XmlRelPosix).ToLowerInvariant()

    $matches = @(
        Get-ChildItem -LiteralPath $rootFull -Recurse -File -Filter $leaf -ErrorAction SilentlyContinue |
            Where-Object {
                $rel = '/' + (([IO.Path]::GetRelativePath($rootFull, $_.FullName) -replace '\\','/').ToLowerInvariant())
                $rel.EndsWith($relNeedle)
            } |
            Sort-Object FullName
    )

    if ($matches.Count -gt 0) { return $matches[0].FullName }
    return ""
}


function Get-GparamXmlFilesUnderRoot {
    param(
        [Parameter(Mandatory=$true)][string]$Root
    )

    $rootFull = [IO.Path]::GetFullPath($Root)
    if (-not (Test-Path -LiteralPath $rootFull -PathType Container)) { return @() }

    return @(
        Get-ChildItem -LiteralPath $rootFull -Recurse -File -Filter '*.gparam.xml' -ErrorAction SilentlyContinue |
            Where-Object { -not (Test-IsGeneratedScratchPath $_.FullName) } |
            Sort-Object FullName |
            ForEach-Object {
                [pscustomobject]@{
                    XmlPath = $_.FullName
                    XmlRelPosix = ConvertTo-PosixPath ([IO.Path]::GetRelativePath($rootFull, $_.FullName))
                }
            }
    )
}

function Read-GparamLightValuesFromWorkRoot {
    param(
        [Parameter(Mandatory=$true)][string]$WorkRoot,
        $Jobs = $null,
        [Parameter(Mandatory=$true)][string]$SourceLabel
    )

    $table = @{}
    $rows = [System.Collections.Generic.List[object]]::new()
    $missing = [System.Collections.Generic.List[object]]::new()
    $seen = New-Object 'System.Collections.Generic.HashSet[string]'

    $xmlFiles = @(Get-GparamXmlFilesUnderRoot -Root $WorkRoot)

    foreach ($x in $xmlFiles) {
        $xmlRel = ConvertTo-PosixPath ([string]$x.XmlRelPosix)
        if (-not $seen.Add($xmlRel)) { continue }

        if (-not (Test-Path -LiteralPath $x.XmlPath -PathType Leaf)) {
            [void]$missing.Add([pscustomobject]@{ Source = $SourceLabel; XmlRel = $xmlRel; XmlPath = $x.XmlPath; Message = 'Missing XML in work root' })
            continue
        }

        $read = Read-GparamLightValuesFromXmlFile -XmlPath $x.XmlPath -XmlRelPosix $xmlRel -SourceLabel $SourceLabel
        Add-GparamLightValuesToTable -TargetTable $table -TargetRows $rows -ReadResult $read
    }

    return [pscustomobject]@{
        Values = $table
        Rows = @($rows.ToArray())
        Missing = @($missing.ToArray())
    }
}




