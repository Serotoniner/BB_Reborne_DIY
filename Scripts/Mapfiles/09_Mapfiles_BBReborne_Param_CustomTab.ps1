                CurrentValue = [string]$Matches[2]
            }
        }

        if ($active -and $content -match '</param>') {
            $active = $false
            $activeName1 = ""
            $activeName2 = ""
        }
    }

    return $table
}


function Read-GparamLightValuesFromNoirPatchRoot {
    param(
        [Parameter(Mandatory=$true)][string]$NoirPatchRoot,
        [Parameter(Mandatory=$true)][string]$WorkRoot,
        $Jobs = $null,
        [Parameter(Mandatory=$true)][string]$SourceLabel
    )

    $table = @{}
    $rows = [System.Collections.Generic.List[object]]::new()
    $missing = [System.Collections.Generic.List[object]]::new()
    $seenPatch = New-Object 'System.Collections.Generic.HashSet[string]'

    $patchFiles = @(
        Get-ChildItem -LiteralPath $NoirPatchRoot -Recurse -File -Filter '*.gparam.xml.patch' -ErrorAction SilentlyContinue |
            Where-Object { $_.Length -gt 0 } |
            Where-Object { -not (Test-IsGeneratedScratchPath $_.FullName) } |
            Sort-Object FullName
    )

    foreach ($patch in $patchFiles) {
        $patchPath = [string]$patch.FullName
        if (-not $seenPatch.Add($patchPath)) { continue }

        $xmlRel = ConvertTo-PosixPath (Get-GparamXmlRelFromPatchFile -PatchPath $patchPath -NoirPatchRoot $NoirPatchRoot)

        if ([string]::IsNullOrWhiteSpace($xmlRel) -or $xmlRel.ToLowerInvariant() -notlike '*.gparam.xml') {
            [void]$missing.Add([pscustomobject]@{ Source = $SourceLabel; XmlRel = $xmlRel; XmlPath = ''; PatchPath = $patchPath; Message = 'Could not infer XML target from Noir patch' })
            continue
        }

        $targetXml = Join-Path $WorkRoot (ConvertTo-WindowsRelPath $xmlRel)
        if (-not (Test-Path -LiteralPath $targetXml -PathType Leaf)) {
            [void]$missing.Add([pscustomobject]@{ Source = $SourceLabel; XmlRel = $xmlRel; XmlPath = $targetXml; PatchPath = $patchPath; Message = 'Missing patched target XML for line mapping' })
            continue
        }

        $lineInfo = Get-GparamLightLineInfoTableFromXmlFile -XmlPath $targetXml
        $patchLines = [System.IO.File]::ReadAllLines($patchPath)
        $inHunk = $false
        $newLineNo = 0
        $patchLineNo = 0
        $readRowsForPatch = 0

        foreach ($rawLine in $patchLines) {
            $patchLineNo++
            $line = [string]$rawLine

            $hm = [regex]::Match($line, '^@@\s+-\d+(?:,\d+)?\s+\+(\d+)(?:,\d+)?\s+@@')
            if ($hm.Success) {
                $inHunk = $true
                $newLineNo = [int]$hm.Groups[1].Value
                continue
            }

            if (-not $inHunk) { continue }
            if ($line.StartsWith('\ No newline')) { continue }

            if ($line.StartsWith('+') -and -not $line.StartsWith('+++')) {
                $payload = $line.Substring(1)

                if ($payload -match '<value\s+id="([^"]+)">\s*(.*?)\s*</value>') {
                    $id = [string]$Matches[1]
                    $value = [string]$Matches[2]

                    if ($lineInfo.ContainsKey($newLineNo)) {
                        $info = $lineInfo[$newLineNo]
                        if ([string]$info.ValueId -eq $id) {
                            $key = Get-GparamLightValueKey -XmlRelPosix $xmlRel -ParamName1 ([string]$info.ParamName1) -ValueId $id
                            $table[$key] = $value
                            $readRowsForPatch++

                            [void]$rows.Add([pscustomobject]@{
                                Source = $SourceLabel
                                XmlRel = $xmlRel
                                ParamName1 = [string]$info.ParamName1
                                ParamName2 = [string]$info.ParamName2
                                ValueId = $id
                                Value = $value
                                XmlPath = $targetXml
                                PatchPath = $patchPath
                                PatchLine = $patchLineNo
                                XmlLine = $newLineNo
                            })
                        }
                    }
                }

                $newLineNo++
                continue
            }

            if ($line.StartsWith(' ') -or $line.Length -eq 0) {
                $newLineNo++
                continue
            }

            # Removed lines do not advance the new-file line counter.
            if ($line.StartsWith('-') -and -not $line.StartsWith('---')) { continue }
        }

        if ($readRowsForPatch -le 0) {
            [void]$missing.Add([pscustomobject]@{ Source = $SourceLabel; XmlRel = $xmlRel; XmlPath = $targetXml; PatchPath = $patchPath; Message = 'No light values read from Noir patch' })
        }
    }

    return [pscustomobject]@{
        Values = $table
        Rows = @($rows.ToArray())
        Missing = @($missing.ToArray())
    }
}



