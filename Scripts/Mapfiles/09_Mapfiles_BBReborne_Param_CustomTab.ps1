}


function Get-GparamXmlRelFromPatchFile {
    param(
        [Parameter(Mandatory=$true)][string]$PatchPath,
        [Parameter(Mandatory=$true)][string]$NoirPatchRoot
    )

    foreach ($line in [System.IO.File]::ReadLines($PatchPath)) {
        $m = [regex]::Match([string]$line, '^\+\+\+\s+(?:b/)?(.+?\.gparam\.xml)\s*$')
        if ($m.Success) {
            $rel = [string]$m.Groups[1].Value
            if ($rel -ne '/dev/null') {
                return ConvertTo-PosixPath $rel
            }
        }
    }

    # Fallback for the final repo layout:
    # <root>\<binder>-gparambnd-dcx\_patches\<xml>.gparam.xml.patch
    $patchLeaf = Split-Path -Leaf $PatchPath
    if ($patchLeaf.ToLowerInvariant().EndsWith('.patch')) {
        $xmlLeaf = $patchLeaf.Substring(0, $patchLeaf.Length - 6)
    }
    else {
        $xmlLeaf = $patchLeaf
    }

    $parent = Split-Path -Parent $PatchPath
    $parentLeaf = Split-Path -Leaf $parent

    if ($parentLeaf -eq '_patches') {
        $binderDir = Split-Path -Leaf (Split-Path -Parent $parent)
        if (-not [string]::IsNullOrWhiteSpace($binderDir)) {
            return ConvertTo-PosixPath (Join-Path $binderDir $xmlLeaf)
        }
    }

    # Last fallback: if the patch is somewhere under the root, strip the root and
    # remove any _patches segment.
    $rootFull = [IO.Path]::GetFullPath($NoirPatchRoot)
    $rel = ConvertTo-PosixPath ([IO.Path]::GetRelativePath($rootFull, $PatchPath))
    $rel = $rel -replace '/_patches/', '/'
    if ($rel.ToLowerInvariant().EndsWith('.patch')) {
        $rel = $rel.Substring(0, $rel.Length - 6)
    }
    return ConvertTo-PosixPath $rel
}

function Resolve-GparamNoirPatchPath {
    param(
        [Parameter(Mandatory=$true)][string]$NoirPatchRoot,
        [Parameter(Mandatory=$true)][string]$XmlRelPosix
    )

    $rootFull = [IO.Path]::GetFullPath($NoirPatchRoot)
    $relWin = ConvertTo-WindowsRelPath $XmlRelPosix
    $relDir = Split-Path -Parent $relWin
    $leaf = Split-Path -Leaf $relWin
    $patchLeaf = $leaf + '.patch'

    $directDir = if ([string]::IsNullOrWhiteSpace($relDir)) { $rootFull } else { Join-Path $rootFull $relDir }
    $direct = Join-Path (Join-Path $directDir '_patches') $patchLeaf
    if (Test-Path -LiteralPath $direct -PathType Leaf) { return $direct }

    $relPosix = ConvertTo-PosixPath $XmlRelPosix
    $relDirPosix = Split-Path -Parent ($relPosix -replace '/', [IO.Path]::DirectorySeparatorChar)
    $needleSuffix = if ([string]::IsNullOrWhiteSpace($relDirPosix)) {
        '/_patches/' + $patchLeaf.ToLowerInvariant()
    } else {
        '/' + (ConvertTo-PosixPath $relDirPosix).ToLowerInvariant() + '/_patches/' + $patchLeaf.ToLowerInvariant()
    }

    $matches = @(
        Get-ChildItem -LiteralPath $rootFull -Recurse -File -Filter $patchLeaf -ErrorAction SilentlyContinue |
            Where-Object {
                $rel = '/' + (([IO.Path]::GetRelativePath($rootFull, $_.FullName) -replace '\\','/').ToLowerInvariant())
                $rel.EndsWith($needleSuffix)
            } |
            Sort-Object FullName
    )

    if ($matches.Count -gt 0) { return $matches[0].FullName }
    return ""
}

