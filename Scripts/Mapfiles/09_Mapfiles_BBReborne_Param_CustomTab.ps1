function Get-GparamXmlAttrValue {
    param(
        [Parameter(Mandatory=$true)][string]$Text,
        [Parameter(Mandatory=$true)][string]$AttrName
    )

    $m = [regex]::Match($Text, ('\b' + [regex]::Escape($AttrName) + '="([^"]*)"'))
