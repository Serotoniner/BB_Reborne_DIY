                    [void]$duplicateRows.Add([pscustomobject]@{
                        XmlRel = $xmlRel
                        Selected = ($dupe.FullName -eq $winner.FullName)
                        Rank = Get-PatchSelectionRank -PatchPath $dupe.FullName -Root $patchRoot
                        PatchPath = $dupe.FullName
                    })
                }

                [void]$selectedPatches.Add($winner)
            }
            else {
                foreach ($pf in $group) { [void]$selectedPatches.Add($pf) }
            }
        }

        $patches = @($selectedPatches | Sort-Object FullName)

        if ($duplicateRows.Count -gt 0) {
            Write-Host ("  De-duplicated {0} duplicate patch candidate entries. Using {1} unique patch target(s)." -f $duplicateRows.Count, $patches.Count) -ForegroundColor Yellow
            $dupePreview = @($duplicateRows | Where-Object { -not $_.Selected } | Select-Object -First 12)
            foreach ($d in $dupePreview) {
                Write-Host ("    SKIP duplicate: {0}" -f $d.PatchPath) -ForegroundColor DarkYellow
            }
        }
    }
    else {
        $patches = @($patchCandidates | Sort-Object FullName -Unique)
    }

    Write-Host ("Using {0} GParam XML patch file(s)." -f $patches.Count)

    $jobs = [System.Collections.Generic.List[object]]::new()
    $matchRows = [System.Collections.Generic.List[object]]::new()

    foreach ($p in $patches) {
        $xmlRel = Get-XmlRelFromPatch $p.FullName
        if (-not $xmlRel) {
            [void]$matchRows.Add([pscustomobject]@{
                PatchPath = $p.FullName
                XmlRel = ""
                ArchiveRel = ""
                Status = "Skip"
                Message = "Could not parse diff --git header"
            })
            continue
        }

        $info = Get-GparamArchiveInfoFromXmlRel $xmlRel
        $origArchive = Join-Path $origRoot $info.ArchiveRelWin

        if (-not (Test-Path -LiteralPath $origArchive -PathType Leaf)) {
            [void]$matchRows.Add([pscustomobject]@{
                PatchPath = $p.FullName
                XmlRel = $info.XmlRelPosix
                ArchiveRel = $info.ArchiveRelPosix
                Status = "MissingOriginal"
                Message = "Original archive not found: $origArchive"
            })
            continue
        }

        [void]$jobs.Add([pscustomobject]@{
            PatchPath = $p.FullName
            PatchLeaf = $p.Name
            XmlRelPosix = $info.XmlRelPosix
            XmlRelWin = ConvertTo-WindowsRelPath $info.XmlRelPosix
            ArchiveRelPosix = $info.ArchiveRelPosix
            ArchiveRelWin = $info.ArchiveRelWin
            ExtractFolderRelPosix = $info.ExtractFolderRelPosix
            ExtractFolderRelWin = $info.ExtractFolderRelWin
            OrigArchive = $origArchive
        })

        [void]$matchRows.Add([pscustomobject]@{
            PatchPath = $p.FullName
            XmlRel = $info.XmlRelPosix
            ArchiveRel = $info.ArchiveRelPosix
            Status = "Matched"
            Message = ""
        })
    }

    Write-Host ("Matched patches: {0} / {1}" -f $jobs.Count, $patches.Count)

    if ($DryRun) {
        Write-Host "DRYRUN: stopping after patch/original matching."
        $completed = $true
        return
    }

    Ensure-Dir $outRoot
    Ensure-Dir $manifestRoot
    Reset-ScratchFolder -Path $workRoot -ExpectedLeaf $WorkDirName

    $matchManifest = Join-Path $manifestRoot "gparam_patch_match_manifest.csv"
    $matchRows | Export-Csv -LiteralPath $matchManifest -NoTypeInformation -Encoding UTF8

    if ($jobs.Count -eq 0) {
        throw "No patches matched original .gparambnd.dcx files. See: $matchManifest"
    }

    $failedMatches = @($matchRows | Where-Object { $_.Status -ne "Matched" })
    if ($failedMatches.Count -gt 0) {
        Write-Host ("  WARN: {0} patch(es) did not match originals. See: {1}" -f $failedMatches.Count, $matchManifest) -ForegroundColor Yellow
    }

    Write-Host ""
    Write-Host "Stage #1: copying original GParam binder DCX files into work folder..."

    $archives = @($jobs | Group-Object ArchiveRelPosix | Sort-Object Name)
    foreach ($grp in $archives) {
        $first = $grp.Group[0]
        $workArchive = Join-Path $workRoot $first.ArchiveRelWin
        Ensure-Dir (Split-Path -Parent $workArchive)
        Copy-Item -LiteralPath $first.OrigArchive -Destination $workArchive -Force
    }

    Write-Host ""
    Write-Host ("Stage #2: decompressing GParam binders with WitchyBND, batchSize={0}..." -f $WitchyBatchSize)

    $archivePaths = @($archives | ForEach-Object { Join-Path $workRoot $_.Group[0].ArchiveRelWin })
    Invoke-WitchyBatchSimple -Exe $WitchyBND -Paths $archivePaths -BatchSize $WitchyBatchSize -Label "WitchyBND decompress"

    $missingExtracts = @()
    foreach ($grp in $archives) {
        $first = $grp.Group[0]
        $extractPath = Join-Path $workRoot $first.ExtractFolderRelWin
        if (-not (Test-Path -LiteralPath $extractPath -PathType Container)) {
            $missingExtracts += [pscustomobject]@{
                ArchiveRel = $first.ArchiveRelPosix
                ExtractFolder = $extractPath
            }
        }
    }

    if ($missingExtracts.Count -gt 0) {
        $missingCsv = Join-Path $outRoot "missing_gparam_extract_folders.csv"
        $missingExtracts | Export-Csv -LiteralPath $missingCsv -NoTypeInformation -Encoding UTF8
        throw "Some GParam archives did not extract to expected folders. See: $missingCsv"
    }

    $vanillaLightRead = $null
    if ($LightSource -eq 'Vanilla') {
        Write-Host ""
        Write-Host "Stage #2b: caching vanilla light values before patching..."
        $vanillaLightRead = Read-GparamLightValuesFromWorkRoot -WorkRoot $workRoot -Jobs $jobs -SourceLabel 'Vanilla'
        Write-Host ("  Cached vanilla light value rows: {0}" -f $vanillaLightRead.Rows.Count)
        if ($vanillaLightRead.Missing.Count -gt 0) {
            $vanillaMissingCsv = Join-Path $manifestRoot "gparam_light_vanilla_missing.csv"
            $vanillaLightRead.Missing | Export-Csv -LiteralPath $vanillaMissingCsv -NoTypeInformation -Encoding UTF8
            Write-Host ("  WARN: {0} vanilla XML source file(s) missing. See: {1}" -f $vanillaLightRead.Missing.Count, $vanillaMissingCsv) -ForegroundColor Yellow
        }
    }

    Write-Host ""
    Write-Host "Stage #3: applying XML patches..."

    $applyRows = [System.Collections.Generic.List[object]]::new()
    $n = 0
    foreach ($j in $jobs) {
        $n++
        Write-Progress -Activity "Apply GParam XML patches" -Status ("{0}/{1}: {2}" -f $n, $jobs.Count, $j.PatchLeaf) -PercentComplete ([int](100.0 * $n / $jobs.Count))

        $row = Invoke-GitApplyPatch `
            -GitExe $GitExe `
            -PatchPath $j.PatchPath `
            -WorkRoot $workRoot `
            -XmlRelPosix $j.XmlRelPosix `
            -PreferThreeWay:$PreferThreeWay

        $row | Add-Member -NotePropertyName ArchiveRel -NotePropertyValue $j.ArchiveRelPosix -Force
        [void]$applyRows.Add($row)

        if (-not $row.Ok) {
            Write-Host ("  FAIL: {0}" -f $j.PatchLeaf) -ForegroundColor Red
            Write-Host ("        {0}" -f $row.Message) -ForegroundColor Red
            if ($row.RejectFiles) { Write-Host ("        Rejects: {0}" -f $row.RejectFiles) -ForegroundColor Red }
        }
    }
    Write-Progress -Activity "Apply GParam XML patches" -Completed

    $applyManifest = Join-Path $manifestRoot "gparam_patch_apply_manifest.csv"
    $applyRows | Export-Csv -LiteralPath $applyManifest -NoTypeInformation -Encoding UTF8

    $failedApply = @($applyRows | Where-Object { -not $_.Ok })
    if ($failedApply.Count -gt 0) {
        throw "Patch apply failed for $($failedApply.Count) XML patch(es). See: $applyManifest"
    }

    if ($LightSource -ne 'Mod') {
        Write-Host ""
        Write-Host ("Stage #3b: applying direct XML light override: {0}" -f $LightSource)

        $lightValues = $null
        $lightSourceRows = @()
        $lightMissingRows = @()

        if ($LightSource -eq 'Vanilla') {
            if ($null -eq $vanillaLightRead) { throw 'Internal error: vanilla light values were not cached before patching.' }
            $lightValues = $vanillaLightRead.Values
            $lightSourceRows = @($vanillaLightRead.Rows)
            $lightMissingRows = @($vanillaLightRead.Missing)
        }
        elseif ($LightSource -eq 'Noir') {
            if (-not [string]::IsNullOrWhiteSpace($LightPresetXmlRoot)) {
                $noirLightRead = Read-GparamLightValuesFromSourceRoot -SourceRoot $LightPresetXmlRoot -Jobs $jobs -SourceLabel 'NoirXmlPreset'
            }
            elseif (-not [string]::IsNullOrWhiteSpace($NoirPatchDir)) {
                $noirLightRead = Read-GparamLightValuesFromNoirPatchRoot -NoirPatchRoot $NoirPatchDir -WorkRoot $workRoot -Jobs $jobs -SourceLabel 'NoirPatch'
            }
            else {
                throw 'Internal error: Noir was selected, but neither LightPresetXmlRoot nor NoirPatchDir was resolved.'
            }

            $lightValues = $noirLightRead.Values
            $lightSourceRows = @($noirLightRead.Rows)
            $lightMissingRows = @($noirLightRead.Missing)

            if ($lightValues.Count -le 0) {
                if (-not [string]::IsNullOrWhiteSpace($LightPresetXmlRoot)) {
                    throw "No Noir light values were read from LightPresetXmlRoot: $LightPresetXmlRoot"
                }
                throw "No Noir light values were read from NoirPatchDir: $NoirPatchDir"
            }
        }

        $lightSourceCsv = Join-Path $manifestRoot "gparam_light_source_values_$($LightSource).csv"
        $lightSourceRows | Export-Csv -LiteralPath $lightSourceCsv -NoTypeInformation -Encoding UTF8

        if ($lightMissingRows.Count -gt 0) {
            $lightMissingCsv = Join-Path $manifestRoot "gparam_light_source_missing_$($LightSource).csv"
            $lightMissingRows | Export-Csv -LiteralPath $lightMissingCsv -NoTypeInformation -Encoding UTF8
            Write-Host ("  WARN: {0} light source XML file(s) missing. See: {1}" -f $lightMissingRows.Count, $lightMissingCsv) -ForegroundColor Yellow
        }

        $overrideRows = [System.Collections.Generic.List[object]]::new()
        $seenOverrideXml = New-Object 'System.Collections.Generic.HashSet[string]'

        # Apply the light override to every XML that has source values, not only to
        # XML files that had a Main/custom patch. Some gparam binders contain extra
        # XMLs such as *_0100 / *_0200 that can need Noir values even when the Main
        # patch set did not contain a separate patch for that XML.
        $overrideXmlRels = @(
            $lightSourceRows |
                ForEach-Object { ConvertTo-PosixPath ([string]$_.XmlRel) } |
                Where-Object { -not [string]::IsNullOrWhiteSpace($_) } |
                Sort-Object -Unique
        )

        if ($overrideXmlRels.Count -le 0) {
            $overrideXmlRels = @(
                $jobs |
                    ForEach-Object { ConvertTo-PosixPath ([string]$_.XmlRelPosix) } |
                    Sort-Object -Unique
            )
        }

        foreach ($xmlRelRaw in $overrideXmlRels) {
            $xmlRel = ConvertTo-PosixPath ([string]$xmlRelRaw)
            if (-not $seenOverrideXml.Add($xmlRel)) { continue }

            $targetXml = Join-Path $workRoot (ConvertTo-WindowsRelPath $xmlRel)
            if (-not (Test-Path -LiteralPath $targetXml -PathType Leaf)) {
                [void]$overrideRows.Add([pscustomobject]@{
                    LightSource = $LightSource
                    XmlRel = $xmlRel
                    XmlPath = $targetXml
                    AppliedRows = 0
                    ChangedRows = 0
                    MissingSourceRows = 0
                    Status = 'MissingTargetXml'
                })
                continue
            }

            $r = Set-GparamLightValuesInXmlFile -XmlPath $targetXml -XmlRelPosix $xmlRel -SourceValues $lightValues -LightSourceLabel $LightSource
            $r | Add-Member -NotePropertyName Status -NotePropertyValue 'OK' -Force
            [void]$overrideRows.Add($r)
        }

        $lightOverrideManifest = Join-Path $manifestRoot "gparam_light_override_manifest.csv"
        $overrideRows | Export-Csv -LiteralPath $lightOverrideManifest -NoTypeInformation -Encoding UTF8

        $changedLightRows = @($overrideRows | Measure-Object -Property ChangedRows -Sum).Sum
        $appliedLightRows = @($overrideRows | Measure-Object -Property AppliedRows -Sum).Sum
        $missingLightRows = @($overrideRows | Measure-Object -Property MissingSourceRows -Sum).Sum
        Write-Host ("  Light override applied rows: {0}; changed rows: {1}; missing source rows: {2}" -f $appliedLightRows, $changedLightRows, $missingLightRows)
        Write-Host ("  Light override manifest: {0}" -f $lightOverrideManifest)
    }

    Write-Host ""
    Write-Host ("Stage #4: recompressing patched GParam folders with WitchyBND, batchSize={0}..." -f $WitchyBatchSize)

    $extractFolders = @($archives | ForEach-Object { Join-Path $workRoot $_.Group[0].ExtractFolderRelWin })
    Invoke-WitchyBatchSimple -Exe $WitchyBND -Paths $extractFolders -BatchSize $WitchyBatchSize -Label "WitchyBND recompress"

    $repackRows = [System.Collections.Generic.List[object]]::new()
    foreach ($grp in $archives) {
        $first = $grp.Group[0]
        $workArchive = Join-Path $workRoot $first.ArchiveRelWin
        $ok = Test-Path -LiteralPath $workArchive -PathType Leaf
        [void]$repackRows.Add([pscustomobject]@{
            ArchiveRel = $first.ArchiveRelPosix
            WorkArchive = $workArchive
            Ok = [bool]$ok
        })
    }

    $repackManifest = Join-Path $manifestRoot "gparam_repack_manifest.csv"
    $repackRows | Export-Csv -LiteralPath $repackManifest -NoTypeInformation -Encoding UTF8

    $failedRepack = @($repackRows | Where-Object { -not $_.Ok })
    if ($failedRepack.Count -gt 0) {
        throw "Repack did not produce expected archive(s). See: $repackManifest"
    }

    Write-Host ""
    Write-Host "Stage #5: writing patched GParam binder DCX files into OutputDir..."

    foreach ($grp in $archives) {
        $first = $grp.Group[0]
        $workArchive = Join-Path $workRoot $first.ArchiveRelWin
        $destArchive = Join-Path $outRoot $first.ArchiveRelWin
        Ensure-Dir (Split-Path -Parent $destArchive)
        Copy-Item -LiteralPath $workArchive -Destination $destArchive -Force
    }

    Write-Host ""
    Write-Host "================ FINAL SUMMARY ================"
    Write-Host ("Patches applied: {0}" -f $jobs.Count)
    Write-Host ("Archives rebuilt: {0}" -f $archives.Count)
    Write-Host ("PatchSearchMode: {0}" -f $PatchSearchMode)
    Write-Host ("PreferThreeWay:  {0}" -f ([bool]$PreferThreeWay))
    Write-Host ("LightSource:     {0}" -f $LightSource)
    if ($LightSource -eq 'Noir') {
    if (-not [string]::IsNullOrWhiteSpace($LightPresetXmlRoot)) { Write-Host ("LightPresetXmlRoot: {0}" -f $LightPresetXmlRoot) }
    if (-not [string]::IsNullOrWhiteSpace($NoirPatchDir)) { Write-Host ("NoirPatchDir: {0}" -f $NoirPatchDir) }
}
    Write-Host ("OutputDir:       {0}" -f $outRoot)
    Write-Host ("Apply manifest:  {0}" -f $applyManifest)
    Write-Host ("Elapsed:         {0}" -f $timer.Elapsed.ToString())

    $completed = $true
}
catch {
    $hadFailure = $true
    throw
}
finally {
    Write-Host ""
    Write-Host "Stage #6: cleanup..."
    if ($DryRun) {
        Write-Host ("  DRY: would remove work folder: {0}" -f $workRoot)
    }
    elseif ($KeepWork -or $hadFailure -or -not $completed) {
        Write-Host ("  Keeping work folder: {0}" -f $workRoot)
        if ($hadFailure -or -not $completed) { Write-Host "  Kept because the run did not complete successfully." -ForegroundColor Yellow }
    }
    else {
        Assert-SafeScratchFolder -Path $workRoot -ExpectedLeaf $WorkDirName
        if (Test-Path -LiteralPath $workRoot -PathType Container) {
            Remove-Item -LiteralPath $workRoot -Recurse -Force
            Write-Host ("  Removed: {0}" -f $workRoot)
        }

        Remove-SafeScratchFolderIfExists `
            -Path $legacyNoirSourceWorkRoot `
            -ExpectedLeaf "_gparam_noir_source_work" `
            -RequiredParent $outRoot `
            -Label "legacy Noir source work folder" `
            -DryRun:$DryRun
    }
}
