function Resolve-GparamLightPresetXmlRoot {
    param(
        [Parameter(Mandatory=$true)][string]$ProjectRoot,
        [string]$RequestedRoot = ""
    )

    $candidates = New-Object System.Collections.Generic.List[string]
    if (-not [string]::IsNullOrWhiteSpace($RequestedRoot)) { [void]$candidates.Add($RequestedRoot) }
    [void]$candidates.Add((Join-Path (Join-Path (Join-Path $ProjectRoot 'LightPresets') 'Noir') 'param\drawparam'))
    [void]$candidates.Add((Join-Path (Join-Path $ProjectRoot 'LightPresets') 'Noir'))
    [void]$candidates.Add((Join-Path (Join-Path (Join-Path $ProjectRoot 'Diffs_noir') 'param') 'drawparam'))

    foreach ($candidate in @($candidates.ToArray())) {
        if ([string]::IsNullOrWhiteSpace($candidate)) { continue }
        if (-not (Test-Path -LiteralPath $candidate -PathType Container)) { continue }
        $xml = @(Get-ChildItem -LiteralPath $candidate -Recurse -File -Filter '*.gparam.xml' -ErrorAction SilentlyContinue | Select-Object -First 1)
        if ($xml.Count -gt 0) { return [IO.Path]::GetFullPath($candidate) }
    }

    return ""
}


function Resolve-GparamNoirPatchRoot {
    param(
        [Parameter(Mandatory=$true)][string]$ProjectRoot,
        [string]$RequestedRoot = ""
    )

    $candidates = New-Object System.Collections.Generic.List[string]
    if (-not [string]::IsNullOrWhiteSpace($RequestedRoot)) { [void]$candidates.Add($RequestedRoot) }
    [void]$candidates.Add((Join-Path (Join-Path (Join-Path $ProjectRoot 'Diffs_noir') 'param') 'drawparam'))
    [void]$candidates.Add((Join-Path (Join-Path $ProjectRoot 'Diffs_noir') 'param'))
    [void]$candidates.Add((Join-Path $ProjectRoot 'Diffs_noir'))

