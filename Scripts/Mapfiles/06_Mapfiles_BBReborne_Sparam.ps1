try {
    Write-Host ("PatchDir:        {0}" -f $patchRoot)
    Write-Host ("OriginalDir:     {0}" -f $origRoot)
    Write-Host ("OutputDir:       {0}" -f $outRoot)
    Write-Host ("WorkDir:         {0}" -f $workRoot)
    Write-Host ("PatchSearchMode: {0}" -f $PatchSearchMode)
    if ($PreferThreeWay) { Write-Host "PreferThreeWay:  enabled" -ForegroundColor Yellow }

    $patchCandidates = @(Find-SgparamXmlPatchFiles -Root $patchRoot -Mode $PatchSearchMode)



    if (-not [string]::IsNullOrWhiteSpace($ParamPrefix)) {
        $patchCandidates = @($patchCandidates | Where-Object {
            $xmlRel = Get-XmlRelFromPatch $_.FullName
            if ($xmlRel) {
                $leaf = Split-Path -Leaf (ConvertTo-WindowsRelPath $xmlRel)
                $leaf.StartsWith($ParamPrefix, [StringComparison]::OrdinalIgnoreCase)
            }
            else {
                $_.Name.StartsWith($ParamPrefix, [StringComparison]::OrdinalIgnoreCase)
            }
        })
        Write-Host ("Filtered S gparam patches by ParamPrefix '{0}'." -f $ParamPrefix)
    }

    Write-Host ("Found {0} non-empty S gparam XML patch candidate file(s)." -f $patchCandidates.Count)
    if ($patchCandidates.Count -eq 0) { Write-Host "Nothing to do."; return }

    if ($PatchSearchMode -eq "AutoDedup") {
        $patchByXmlRel = @{}
        $duplicateRows = [System.Collections.Generic.List[object]]::new()

        foreach ($pf in $patchCandidates) {
            $xmlRel = Get-XmlRelFromPatch $pf.FullName
            if (-not $xmlRel) {
                $xmlRel = "__unparsed__/{0}" -f $pf.FullName.ToLowerInvariant()
            }

            if (-not $patchByXmlRel.ContainsKey($xmlRel)) {
                $patchByXmlRel[$xmlRel] = [System.Collections.Generic.List[object]]::new()
            }
            [void]$patchByXmlRel[$xmlRel].Add($pf)
        }

        $selectedPatches = [System.Collections.Generic.List[object]]::new()

        foreach ($xmlRel in ($patchByXmlRel.Keys | Sort-Object)) {
            $group = @($patchByXmlRel[$xmlRel])
            if ($group.Count -gt 1 -and -not $xmlRel.StartsWith("__unparsed__/")) {
                $winner = @($group | Sort-Object @{ Expression = { Get-PatchSelectionRank -PatchPath $_.FullName -Root $patchRoot } }, FullName | Select-Object -First 1)[0]

                foreach ($dupe in $group) {
                    [void]$duplicateRows.Add([pscustomobject]@{
                        XmlRel = $xmlRel
                        Selected = ($dupe.FullName -eq $winner.FullName)
                        Rank = Get-PatchSelectionRank -PatchPath $dupe.FullName -Root $patchRoot
                        PatchPath = $dupe.FullName
                    })
                }

                [void]$selectedPatches.Add($winner)
            }
            else {
                foreach ($pf in $group) { [void]$selectedPatches.Add($pf) }
            }
        }

        $patches = @($selectedPatches | Sort-Object FullName)

        if ($duplicateRows.Count -gt 0) {
            Write-Host ("  De-duplicated {0} duplicate patch candidate entries. Using {1} unique patch target(s)." -f $duplicateRows.Count, $patches.Count) -ForegroundColor Yellow
            $dupePreview = @($duplicateRows | Where-Object { -not $_.Selected } | Select-Object -First 12)
            foreach ($d in $dupePreview) {
                Write-Host ("    SKIP duplicate: {0}" -f $d.PatchPath) -ForegroundColor DarkYellow
            }
        }
    }
    else {
        $patches = @($patchCandidates | Sort-Object FullName -Unique)
    }

    Write-Host ("Using {0} S gparam XML patch file(s)." -f $patches.Count)

    $jobs = [System.Collections.Generic.List[object]]::new()
    $matchRows = [System.Collections.Generic.List[object]]::new()

    foreach ($p in $patches) {
        $xmlRel = Get-XmlRelFromPatch $p.FullName
        if (-not $xmlRel) {
            [void]$matchRows.Add([pscustomobject]@{
                PatchPath = $p.FullName
                XmlRel = ""
                ArchiveRel = ""
                Status = "Skip"
                Message = "Could not parse diff --git header"
            })
            continue
        }

        $info = Get-SgparamArchiveInfoFromXmlRel $xmlRel
        $origArchive = Join-Path $origRoot $info.ArchiveRelWin

        if (-not (Test-Path -LiteralPath $origArchive -PathType Leaf)) {
            [void]$matchRows.Add([pscustomobject]@{
                PatchPath = $p.FullName
                XmlRel = $info.XmlRelPosix
                ArchiveRel = $info.ArchiveRelPosix
                Status = "MissingOriginal"
                Message = "Original archive not found: $origArchive"
            })
            continue
        }

        [void]$jobs.Add([pscustomobject]@{
            PatchPath = $p.FullName
            PatchLeaf = $p.Name
            XmlRelPosix = $info.XmlRelPosix
            XmlRelWin = $info.XmlRelWin
            ArchiveRelPosix = $info.ArchiveRelPosix
            ArchiveRelWin = $info.ArchiveRelWin
            OrigArchive = $origArchive
        })

        [void]$matchRows.Add([pscustomobject]@{
            PatchPath = $p.FullName
            XmlRel = $info.XmlRelPosix
            ArchiveRel = $info.ArchiveRelPosix
            Status = "Matched"
            Message = ""
        })
    }

    Write-Host ("Matched patches: {0} / {1}" -f $jobs.Count, $patches.Count)

    if ($DryRun) {
        Write-Host "DRYRUN: stopping after patch/original matching."
        $completed = $true
        return
    }

    Ensure-Dir $outRoot
    Reset-ScratchFolder -Path $workRoot -ExpectedLeaf $WorkDirName

    $matchManifest = Join-Path $manifestRoot "sgparam_patch_match_manifest.csv"
    $matchRows | Export-Csv -LiteralPath $matchManifest -NoTypeInformation -Encoding UTF8

    if ($jobs.Count -eq 0) {
        throw "No patches matched original *.gparam.dcx files. See: $matchManifest"
    }

    $failedMatches = @($matchRows | Where-Object { $_.Status -ne "Matched" })
    if ($failedMatches.Count -gt 0) {
        Write-Host ("  WARN: {0} patch(es) did not match originals. See: {1}" -f $failedMatches.Count, $matchManifest) -ForegroundColor Yellow
    }

    Write-Host ""
    Write-Host "Stage #1: copying original S gparam DCX files into work folder..."

    $archives = @($jobs | Group-Object ArchiveRelPosix | Sort-Object Name)
    foreach ($grp in $archives) {
        $first = $grp.Group[0]
        $workArchive = Join-Path $workRoot $first.ArchiveRelWin
        Ensure-Dir (Split-Path -Parent $workArchive)
        Copy-Item -LiteralPath $first.OrigArchive -Destination $workArchive -Force
    }

    Write-Host ""
    Write-Host ("Stage #2: extracting S gparam DCX with WitchyBND, batchSize={0}..." -f $WitchyBatchSize)

    $archivePaths = @($archives | ForEach-Object { Join-Path $workRoot $_.Group[0].ArchiveRelWin })
    Invoke-WitchyBatchSimple -Exe $WitchyBND -Paths $archivePaths -BatchSize $WitchyBatchSize -Label "WitchyBND extract"

    $missingXml = @()
    foreach ($grp in $archives) {
        $first = $grp.Group[0]
        $xmlPath = (Join-Path $workRoot $first.ArchiveRelWin) + ".xml"
        if (-not (Test-Path -LiteralPath $xmlPath -PathType Leaf)) {
            $missingXml += [pscustomobject]@{
                ArchiveRel = $first.ArchiveRelPosix
                MissingXml = $xmlPath
            }
        }
    }

    if ($missingXml.Count -gt 0) {
        $missingCsv = Join-Path $manifestRoot "missing_sgparam_xml_after_witchy.csv"
        $missingXml | Export-Csv -LiteralPath $missingCsv -NoTypeInformation -Encoding UTF8
        throw "Some S gparam archives did not extract to expected XML files. See: $missingCsv"
    }

    Write-Host ""
    Write-Host "Stage #3: applying XML patches..."

    $applyRows = [System.Collections.Generic.List[object]]::new()
    $n = 0

    foreach ($j in $jobs) {
        $n++
        Write-Progress -Activity "Apply S gparam XML patches" -Status ("{0}/{1}: {2}" -f $n, $jobs.Count, $j.PatchLeaf) -PercentComplete ([int](100.0 * $n / $jobs.Count))

        $row = Invoke-GitApplyPatch `
            -GitExe $GitExe `
            -PatchPath $j.PatchPath `
            -WorkRoot $workRoot `
            -XmlRelPosix $j.XmlRelPosix `
            -PreferThreeWay:$PreferThreeWay

        $row | Add-Member -NotePropertyName ArchiveRel -NotePropertyValue $j.ArchiveRelPosix -Force
        [void]$applyRows.Add($row)

        if (-not $row.Ok) {
            Write-Host ("  FAIL: {0}" -f $j.PatchLeaf) -ForegroundColor Red
            Write-Host ("        {0}" -f $row.Message) -ForegroundColor Red
            if ($row.RejectFiles) { Write-Host ("        Rejects: {0}" -f $row.RejectFiles) -ForegroundColor Red }
        }
    }
    Write-Progress -Activity "Apply S gparam XML patches" -Completed

    $applyManifest = Join-Path $manifestRoot "sgparam_patch_apply_manifest.csv"
    $applyRows | Export-Csv -LiteralPath $applyManifest -NoTypeInformation -Encoding UTF8

    $failedApply = @($applyRows | Where-Object { -not $_.Ok })
    if ($failedApply.Count -gt 0) {
        throw "Patch apply failed for $($failedApply.Count) XML patch(es). See: $applyManifest"
    }

    Write-Host ""
    Write-Host ("Stage #4: recompressing patched S gparam XML files with WitchyBND, batchSize={0}..." -f $WitchyBatchSize)

    $xmlPaths = @($archives | ForEach-Object { (Join-Path $workRoot $_.Group[0].ArchiveRelWin) + ".xml" })
    Invoke-WitchyBatchSimple -Exe $WitchyBND -Paths $xmlPaths -BatchSize $WitchyBatchSize -Label "WitchyBND recompress"

    $repackRows = [System.Collections.Generic.List[object]]::new()
    foreach ($grp in $archives) {
        $first = $grp.Group[0]
        $workArchive = Join-Path $workRoot $first.ArchiveRelWin
        $ok = Test-Path -LiteralPath $workArchive -PathType Leaf
        [void]$repackRows.Add([pscustomobject]@{
            ArchiveRel = $first.ArchiveRelPosix
            WorkArchive = $workArchive
            Ok = [bool]$ok
        })
    }

    $repackManifest = Join-Path $manifestRoot "sgparam_repack_manifest.csv"
    $repackRows | Export-Csv -LiteralPath $repackManifest -NoTypeInformation -Encoding UTF8

    $failedRepack = @($repackRows | Where-Object { -not $_.Ok })
    if ($failedRepack.Count -gt 0) {
        throw "Repack did not produce expected S gparam DCX file(s). See: $repackManifest"
    }

    Write-Host ""
    Write-Host "Stage #5: writing patched S gparam DCX files into OutputDir..."

    foreach ($grp in $archives) {
        $first = $grp.Group[0]
        $workArchive = Join-Path $workRoot $first.ArchiveRelWin
        $destArchive = Join-Path $outRoot $first.ArchiveRelWin
        Ensure-Dir (Split-Path -Parent $destArchive)
        Copy-Item -LiteralPath $workArchive -Destination $destArchive -Force
    }

    Write-Host ""
    Write-Host "================ FINAL SUMMARY ================"
    Write-Host ("Patches applied: {0}" -f $jobs.Count)
    Write-Host ("Archives rebuilt: {0}" -f $archives.Count)
    Write-Host ("PatchSearchMode: {0}" -f $PatchSearchMode)
    Write-Host ("PreferThreeWay:  {0}" -f ([bool]$PreferThreeWay))
    Write-Host ("OutputDir:       {0}" -f $outRoot)
    Write-Host ("Apply manifest:  {0}" -f $applyManifest)
    Write-Host ("Elapsed:         {0}" -f $timer.Elapsed.ToString())

    $completed = $true
}
catch {
    $hadFailure = $true
    throw
}
finally {
    Write-Host ""
    Write-Host "Stage #6: cleanup..."
    if ($DryRun) {
        Write-Host ("  DRY: would remove work folder: {0}" -f $workRoot)
    }
    elseif ($KeepWork -or $hadFailure -or -not $completed) {
        Write-Host ("  Keeping work folder: {0}" -f $workRoot)
        if ($hadFailure -or -not $completed) { Write-Host "  Kept because the run did not complete successfully." -ForegroundColor Yellow }
    }
    else {
        Assert-SafeScratchFolder -Path $workRoot -ExpectedLeaf $WorkDirName
        if (Test-Path -LiteralPath $workRoot -PathType Container) {
            Remove-Item -LiteralPath $workRoot -Recurse -Force
            Write-Host ("  Removed: {0}" -f $workRoot)
        }
    }
}
