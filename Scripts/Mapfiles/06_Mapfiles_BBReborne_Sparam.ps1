<#
    06_Mapfiles_BBReborne_Sparam.ps1

    Applies XML patches generated by Compare-SgparamXmlPatches.ps1 to original
    *.gparam.dcx files, then repacks them with WitchyBND.

    Expected patch target paths look like:
        s22_00_0030.gparam.dcx.xml

    That maps back to:
        s22_00_0030.gparam.dcx

    Notes:
    - PatchDir is read-only input.
    - OriginalDir is read-only input.
    - OutputDir receives patched/repacked DCX files and scratch work.
    - Only the safe scratch folder leaf named by -WorkDirName may be deleted/recreated.
#>

